@pytest.mark.parametrize("name", SPECTRA_NAMES)
def test_reference_spectrum(name: str) -> None:
    """Re-run do_simulation for a reference case and compare to stored intensity."""
    spinsystem, experiment, simopt, expected = _load_reference(name)
    result = do_simulation(spinsystem, experiment, simopt)
    assert result.shape == expected.shape
    np.testing.assert_allclose(result, expected, rtol=1e-10, atol=1e-12)


def test_reference_spectra_have_nonzero_variance() -> None:
    """All reference spectra should have meaningful structure (not flat lines)."""
    for name in SPECTRA_NAMES:
        _, _, _, intensity = _load_reference(name)
        assert np.std(intensity) > 0, f"{name} has zero variance"
        assert np.any(intensity != 0), f"{name} is all zeros"


def test_reference_spectra_have_negative_and_positive() -> None:
    """Spin-correlated radical pairs produce both absorptive and emissive lines."""
    for name in SPECTRA_NAMES:
        _, _, _, intensity = _load_reference(name)
        assert np.any(intensity > 0), f"{name} has no positive intensities"
        assert np.any(intensity < 0), f"{name} has no negative intensities"


def test_swap_pair_s3_s4_have_similar_sums() -> None:
    """S3 and S4 differ only by donor/acceptor swap, so spectral sums should be close."""
    _, _, _, s3 = _load_reference("S3")
    _, _, _, s4 = _load_reference("S4")
    assert abs(s3.sum() - s4.sum()) < 0.1 * max(abs(s3.sum()), abs(s4.sum()))
